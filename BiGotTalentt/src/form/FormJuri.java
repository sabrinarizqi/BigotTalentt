   public void loadDataPendaftaran() {
   String sql = "SELECT p.id, u.username AS nama_siswa, l.nama_lomba, p.status_kelolosan, p.catatan " +
                 "FROM pendaftaran p " +
                 "JOIN users u ON p.user_id = u.id " +
                 "JOIN lomba l ON p.lomba_id = l.id"; // Menggunakan l.id sesuai kolom primary key di tabel lomba
    
    try {
        java.sql.Connection conn = Koneksi.configDB();
        java.sql.Statement st = conn.createStatement();
        java.sql.ResultSet rs = st.executeQuery(sql);
        
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblSiswa.getModel();
        model.setRowCount(0); // Kosongkan tabel dulu
        
        while (rs.next()) {
            String status = rs.getString("status_kelolosan");
            String catatan = rs.getString("catatan");
            String hasilJuri = status;
            
            if (catatan != null && !catatan.trim().isEmpty()) {
                hasilJuri += " (" + catatan + ")";
            }

            model.addRow(new Object[]{
                rs.getString("id"),
                rs.getString("nama_siswa"),
                rs.getString("nama_lomba"),
                hasilJuri
            });
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
    }
   }

