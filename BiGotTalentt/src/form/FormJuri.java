    private void tblSiswaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSiswaMouseClicked
        // TODO add your handling code here:
       int row = tblSiswa.getSelectedRow();
    if (row != -1) {
        // 1. Ambil ID dari kolom pertama (indeks 0)
        idPendaftaranTerpilih = tblSiswa.getValueAt(row, 0).toString();
        
        // 2. (Opsional) Jika di sebelah tulisan "Penilaian untuk ID :" ada JLabel untuk menampilkan ID, 
        // ganti 'lblId' dengan nama variabel label tersebut di form kamu:
        // lblId.setText(idPendaftaranTerpilih);

        // 3. Mengambil data Hasil Juri (Kolom 3) untuk memecah Status dan Catatan
        String hasilJuri = tblSiswa.getValueAt(row, 3).toString();
        
        // Jika formatnya "Status (Catatan)", kita pisahkan kembali agar masuk ke ComboBox dan Textarea
        if (hasilJuri.contains("(")) {
            String status = hasilJuri.substring(0, hasilJuri.indexOf("(")).trim();
            String catatan = hasilJuri.substring(hasilJuri.indexOf("(") + 1, hasilJuri.indexOf(")")).trim();
            
            cmbStatus.setSelectedItem(status);
            txtCatatan.setText(catatan);
        } else {
            cmbStatus.setSelectedItem(hasilJuri);
            txtCatatan.setText("");
        }
    }

    }//GEN-LAST:event_tblSiswaMouseClicked

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        if (idPendaftaranTerpilih == null || idPendaftaranTerpilih.equals("")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih peserta dari tabel terlebih dahulu!");
        return;
    }

    String status = cmbStatus.getSelectedItem().toString();
    String catatan = txtCatatan.getText().trim();

    if (status.equalsIgnoreCase("Tidak Lolos") && catatan.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Harap berikan catatan alasan tidak lolos!");
        return;
    }

    try {
        java.sql.Connection conn = Koneksi.configDB();
        String sql = "UPDATE pendaftaran SET status_kelolosan = ?, catatan = ? WHERE id = ?";
        java.sql.PreparedStatement ps = conn.prepareStatement(sql);
        
        ps.setString(1, status);
        ps.setString(2, catatan);
        ps.setString(3, idPendaftaranTerpilih);

        int updated = ps.executeUpdate();
        if (updated > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Penilaian berhasil disimpan!");
            loadDataPendaftaran(); // Refresh data tabel
            resetForm();           // Bersihkan input
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSimpanActionPerformed

       

