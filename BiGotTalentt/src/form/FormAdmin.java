    // Fungsi untuk menampilkan data dari database ke jTable1
    private void loadData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama Lomba");

        try {
            Connection c = Koneksi.configDB();
            Statement s = c.createStatement();
            String sql = "SELECT * FROM lomba";
            ResultSet r = s.executeQuery(sql);

            while (r.next()) {
                model.addRow(new Object[]{
                    r.getString("id"),
                    r.getString("nama_lomba")
                });
            }
            tblPendaftar.setModel(model); 
       } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error di: " + e.toString());
    }
    }

