    private void btnSimpanLombaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanLombaActionPerformed
        // TODO add your handling code here:
        
       try {
        String namaLomba = txtNamaLomba.getText();
        
        // Validasi agar tidak kosong
        if(namaLomba.isEmpty()){
            JOptionPane.showMessageDialog(this, "Nama lomba tidak boleh kosong!");
            return;
        }
        
        Connection c = Koneksi.configDB();
        Statement s = c.createStatement();
        
        // Perintah SQL untuk memasukkan data ke tabel lomba
        String sql = "INSERT INTO lomba (nama_lomba) VALUES ('" + namaLomba + "')";
        s.executeUpdate(sql);
        
        JOptionPane.showMessageDialog(this, "Data Lomba Berhasil Disimpan!");
        txtNamaLomba.setText(""); // Mengosongkan kembali kolom input
        
        loadData(); // <-- TAMBAHKAN BARIS INI SUPAYA TABEL OTOMATIS REFRESH
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSimpanLombaActionPerformed

    private void btnUbahStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahStatusActionPerformed
        // TODO add your handling code here:
        int baris = tblPendaftar.getSelectedRow();
    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu!");
        return;
    }
    
    // Mengambil ID dari baris yang dipilih (kolom ke-0)
    String id = tblPendaftar.getValueAt(baris, 0).toString();
    
    // Dialog pilihan status baru
    String[] pilihanStatus = {"Dokumen dalam Tinjauan", "Jadwal Briefing", "Tahap Pelatihan"};
    String statusBaru = (String) JOptionPane.showInputDialog(
        this, 
        "Pilih Status Baru:", 
        "Update Status Pendaftaran", 
        JOptionPane.QUESTION_MESSAGE, 
        null, 
        pilihanStatus, 
        pilihanStatus[0]
    );
    
    if (statusBaru != null) {
        try {
            Connection c = Koneksi.configDB();
            Statement s = c.createStatement();
            String sql = "UPDATE pendaftaran SET status = '" + statusBaru + "' WHERE id = '" + id + "'";
            s.executeUpdate(sql);
            
            JOptionPane.showMessageDialog(this, "Status berhasil diperbarui!");
            loadData(); // Refresh tabel setelah diubah
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah status: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnUbahStatusActionPerformed

